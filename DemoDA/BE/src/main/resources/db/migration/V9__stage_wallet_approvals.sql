ALTER TABLE users ADD COLUMN wallet_address varchar(42);
ALTER TABLE batches
    ADD COLUMN wallet_registry_address varchar(42),
    ADD COLUMN wallet_registry_chain_id numeric(78, 0);
ALTER TABLE stage_anchor_transactions ADD COLUMN approving_wallet varchar(42);

CREATE TABLE stage_wallet_approvals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id bigint NOT NULL REFERENCES batches(id) ON DELETE CASCADE,
    stage varchar(30) NOT NULL,
    wallet_address varchar(42) NOT NULL,
    merkle_root varchar(66) NOT NULL,
    deadline bigint NOT NULL,
    signature varchar(132) NOT NULL,
    UNIQUE (batch_id, stage)
);
