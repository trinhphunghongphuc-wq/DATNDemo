CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_role varchar(30) NOT NULL,
    batch_id bigint NOT NULL REFERENCES batches(id) ON DELETE CASCADE,
    event_type varchar(40) NOT NULL,
    title varchar(200) NOT NULL,
    message varchar(500) NOT NULL,
    created_at timestamptz NOT NULL,
    read_at timestamptz,
    CONSTRAINT uk_notification_recipient_event_batch
        UNIQUE (recipient_id, event_type, batch_id)
);
CREATE INDEX ix_notifications_inbox
    ON notifications (recipient_id, recipient_role, created_at DESC, id DESC);
CREATE INDEX ix_notifications_unread
    ON notifications (recipient_id, recipient_role) WHERE read_at IS NULL;
