CREATE TABLE batch_return_cases (
    batch_id BIGINT PRIMARY KEY REFERENCES batches(id),
    status VARCHAR(30) NOT NULL CHECK (status IN
        ('REQUESTED','APPROVED','IN_TRANSIT','QUARANTINED','INSPECTED','DECIDED','CLOSED')),
    requested_weight NUMERIC NOT NULL CHECK (requested_weight > 0),
    received_weight NUMERIC CHECK (received_weight >= 0),
    vehicle_id BIGINT REFERENCES vehicles(id),
    warehouse_name VARCHAR(200),
    warehouse_address VARCHAR(300),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE batch_return_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES batch_return_cases(batch_id),
    actor_id BIGINT NOT NULL,
    actor_role VARCHAR(20) NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    details TEXT NOT NULL
);

CREATE INDEX batch_return_events_case_idx ON batch_return_events(batch_id, id);
CREATE UNIQUE INDEX batch_return_one_step_idx ON batch_return_events(batch_id, event_type)
    WHERE event_type NOT IN ('TELEMETRY', 'EXECUTED');
CREATE UNIQUE INDEX batch_return_active_vehicle_idx ON batch_return_cases(vehicle_id)
    WHERE status = 'IN_TRANSIT';
